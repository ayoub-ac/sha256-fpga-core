# Generate 100 random HMAC-SHA-256 vectors for cross-validation against the
# DUT. Output is a C header dumped to stdout; the Makefile pipes it into
# tb/hmac_random_vectors.h.
#
# Each entry is:
#   - key bytes (1..32, never zero-length to keep the wrapper simple)
#   - message bytes (0..200, varied length)
#   - expected HMAC-SHA-256(key, message) hex digest
#
# Reference: RFC 2104 / FIPS-198-1, hashlib.new('sha256') / hmac.new().

import hmac
import hashlib
import random
import sys

random.seed(0xBEEF)
N = 100

print("// Auto-generated by tb/gen_hmac_vectors.py - DO NOT EDIT BY HAND.")
print("// Source of truth: hmac.new(key, msg, hashlib.sha256).hexdigest()")
print("//")
print("// Each entry: random key (1..32 bytes), random message (0..200 bytes),")
print("// expected MAC hex.")
print()
print("#ifndef HMAC_RANDOM_VECTORS_H")
print("#define HMAC_RANDOM_VECTORS_H")
print()
print("#include <cstddef>")
print("#include <cstdint>")
print()
print("struct HmacVec {")
print("    const uint8_t* key;")
print("    size_t         key_len;     // bytes")
print("    const uint8_t* msg;")
print("    size_t         msg_len;     // bytes")
print("    const char*    mac_hex;     // 64-char hex string")
print("};")
print()

vectors = []
for i in range(N):
    klen = random.randint(1, 32)
    mlen = random.randint(0, 200)
    key = bytes(random.randint(0, 255) for _ in range(klen))
    msg = bytes(random.randint(0, 255) for _ in range(mlen))
    mac = hmac.new(key, msg, hashlib.sha256).hexdigest()
    vectors.append((key, msg, mac))
    # Emit byte arrays for this vector.
    key_str = ", ".join(f"0x{b:02x}" for b in key)
    print(f"static const uint8_t kHmacKey_{i}[] = {{ {key_str} }};")
    if mlen == 0:
        print(f"static const uint8_t kHmacMsg_{i}[1] = {{ 0 }}; // unused (len=0)")
    else:
        msg_str = ", ".join(f"0x{b:02x}" for b in msg)
        print(f"static const uint8_t kHmacMsg_{i}[] = {{ {msg_str} }};")

print()
print(f"static const HmacVec kHmacRandomVectors[] = {{")
for i, (key, msg, mac) in enumerate(vectors):
    print(f"    {{ kHmacKey_{i}, {len(key)}, kHmacMsg_{i}, {len(msg)}, \"{mac}\" }},")
print("};")
print()
print(f"static constexpr size_t kHmacRandomVectorCount = {N};")
print()
print("#endif")
