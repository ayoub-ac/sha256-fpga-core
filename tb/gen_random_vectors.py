"""
Generate random SHA-256 test vectors for the C++ Verilator harness.

Output: a C++ header (random_vectors.h) defining a static array of
{message_bytes, message_len, expected_digest} records. The harness in
sim_main.cpp includes this header and runs each vector through the DUT,
comparing against the expected digest computed here by the Python stdlib
hashlib.sha256.

Strategy:
  * 1000 random messages with lengths drawn from the union of:
      - all of [0..130]        (covers single-block and two-block boundaries)
      - random lengths in [131..2000]  (multi-block)
  * Each random message has hashlib.sha256 applied; both the message bytes
    and the digest are emitted to the header.

Run: `python tb/gen_random_vectors.py > tb/random_vectors.h`
(invoked by `make regen_vectors`).

This script is deterministic given a fixed seed so the regenerated header
is reproducible across machines.
"""

import hashlib
import os
import random
import sys


def main() -> int:
    random.seed(0xCA75CA75)

    n_total = 1000
    short_lengths = list(range(0, 131))           # 131 entries
    long_lengths = [random.randint(131, 2000)
                    for _ in range(n_total - len(short_lengths))]
    lengths = short_lengths + long_lengths
    random.shuffle(lengths)

    out = sys.stdout
    out.write("// SPDX-License-Identifier: GPL-3.0-or-later OR LicenseRef-Commercial\n")
    out.write("// AUTO-GENERATED by tb/gen_random_vectors.py.\n"
              "// Do not edit by hand; regenerate with `make regen_vectors`.\n")
    out.write("#pragma once\n")
    out.write("#include <cstdint>\n")
    out.write("#include <cstddef>\n\n")
    out.write("struct RandomVec {\n"
              "    const uint8_t* msg;\n"
              "    size_t         msg_len;\n"
              "    const char*    digest_hex;\n"
              "};\n\n")

    # Emit each message as a static array, then emit the table referencing
    # them. We use a single big arena to avoid 1000 named symbols.
    msgs = []
    digests = []
    for length in lengths:
        msg = bytes(random.randint(0, 255) for _ in range(length))
        digest = hashlib.sha256(msg).hexdigest()
        msgs.append(msg)
        digests.append(digest)

    # Arena: one big flat array with all messages back-to-back.
    out.write("static const uint8_t kRandomArena[] = {\n")
    arena_pos = []
    pos = 0
    flat = bytearray()
    for msg in msgs:
        arena_pos.append(pos)
        flat.extend(msg)
        pos += len(msg)
    flat.append(0)  # sentinel so kRandomArena + N is always valid
    for i in range(0, len(flat), 16):
        chunk = flat[i:i+16]
        out.write("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
    out.write("};\n\n")

    # Table
    out.write(f"static const RandomVec kRandomVectors[] = {{\n")
    for i, (msg, dig) in enumerate(zip(msgs, digests)):
        if len(msg) == 0:
            ptr = "kRandomArena + 0"
        else:
            ptr = f"kRandomArena + {arena_pos[i]}"
        out.write(f"    {{ {ptr}, {len(msg)}u, \"{dig}\" }},\n")
    out.write("};\n\n")
    out.write(f"static constexpr size_t kRandomVectorCount ="
              f" sizeof(kRandomVectors) / sizeof(kRandomVectors[0]);\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
